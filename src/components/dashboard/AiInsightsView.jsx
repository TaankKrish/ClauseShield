import React from 'react';
import { Eye, Sparkles, AlertCircle, ArrowRight } from 'lucide-react';
import { Card } from '../common/Card.jsx';
import { Button } from '../common/Button.jsx';
import { Badge } from '../common/Badge.jsx';

export function AiInsightsView({
  aiInsights,
  loading,
  error,
  onGenerate,
}) {
  if (!aiInsights && !loading && !error) {
    return (
      <Card className="p-6 border-slate-800 bg-slate-900/40 text-center space-y-3">
        <div className="w-10 h-10 rounded-xl bg-amber-500/10 border border-amber-500/20 text-amber-400 flex items-center justify-center mx-auto">
          <Eye className="w-5 h-5" />
        </div>
        <h4 className="text-sm font-bold text-white">Additional AI Observations</h4>
        <p className="text-xs text-slate-400 max-w-md mx-auto leading-relaxed">
          Uncover subtle contractual imbalances, missing terms, and practical blind spots that fall outside codified statutory rules.
        </p>
        <Button variant="outline" size="sm" onClick={onGenerate} className="text-xs">
          <Sparkles className="w-3.5 h-3.5 mr-1.5 text-amber-400" />
          <span>Discover AI Insights</span>
        </Button>
      </Card>
    );
  }

  if (loading) {
    return (
      <Card className="p-8 border-slate-800 text-center space-y-3">
        <div className="w-8 h-8 border-2 border-amber-500 border-t-transparent rounded-full animate-spin mx-auto" />
        <p className="text-xs text-slate-300">Scanning for subtle contractual blind spots...</p>
      </Card>
    );
  }

  if (error) {
    return (
      <Card className="p-4 border-red-900/40 bg-red-950/20 text-xs text-red-300 flex items-center justify-between">
        <span>Failed to generate insights: {error}</span>
        <Button variant="outline" size="sm" onClick={onGenerate}>Retry</Button>
      </Card>
    );
  }

  const insights = aiInsights.insights || [];

  return (
    <Card className="p-6 border-slate-800 bg-slate-900/60 space-y-5">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-slate-800 pb-3">
        <div className="flex items-center space-x-2">
          <div className="w-8 h-8 rounded-lg bg-amber-500/10 border border-amber-500/20 flex items-center justify-center text-amber-400">
            <Eye className="w-4 h-4" />
          </div>
          <div>
            <h4 className="text-sm font-bold text-white">AI-Generated Contractual Observations</h4>
            <span className="text-[11px] text-slate-400 font-mono">
              Unassessed observations beyond deterministic rules
            </span>
          </div>
        </div>

        <Badge variant="amber">AI Observation</Badge>
      </div>

      <div className="p-3 rounded-xl bg-amber-950/20 border border-amber-800/30 text-xs text-amber-300">
        ⚠️ <strong>Note:</strong> These observations are generated by AI analysis to highlight practical ambiguities. They do not represent legal rulings and do not modify deterministic statutory rule results.
      </div>

      <div className="space-y-3">
        {insights.map((item, idx) => (
          <div
            key={idx}
            className="p-4 rounded-xl bg-slate-950 border border-slate-800 hover:border-slate-700 transition-colors space-y-3"
          >
            <div className="flex items-center justify-between">
              <div className="flex items-center space-x-2">
                <span className="text-xs font-mono font-bold text-amber-400">{item.id || `OBS-${idx + 1}`}</span>
                {item.clauseId && (
                  <span className="text-[11px] font-mono text-slate-400 bg-slate-900 px-2 py-0.5 rounded border border-slate-800">
                    Ref: {item.clauseId}
                  </span>
                )}
              </div>
              <span className="text-[10px] font-semibold tracking-wider text-amber-400 uppercase bg-amber-500/10 px-2 py-0.5 rounded border border-amber-500/20">
                {item.label || 'AI-Generated Observation'}
              </span>
            </div>

            <p className="text-xs sm:text-sm font-medium text-slate-100 leading-relaxed">
              {item.observation}
            </p>

            {item.potentialRisk && (
              <div className="p-2.5 rounded-lg bg-slate-900 border border-slate-800 text-xs text-slate-300 flex items-start space-x-2">
                <AlertCircle className="w-3.5 h-3.5 text-amber-400 shrink-0 mt-0.5" />
                <span>
                  <strong className="text-slate-400">Practical Risk: </strong>
                  {item.potentialRisk}
                </span>
              </div>
            )}

            {item.recommendedAction && (
              <div className="p-2.5 rounded-lg bg-emerald-950/20 border border-emerald-900/40 text-xs text-slate-300 flex items-start space-x-2">
                <ArrowRight className="w-3.5 h-3.5 text-emerald-400 shrink-0 mt-0.5" />
                <span>
                  <strong className="text-emerald-400">Recommended Safeguard: </strong>
                  {item.recommendedAction}
                </span>
              </div>
            )}
          </div>
        ))}
      </div>
    </Card>
  );
}

